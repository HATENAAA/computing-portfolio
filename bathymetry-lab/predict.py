"""Apply a trusted exported model to quality-controlled reflectance samples."""
import argparse
import csv
import hashlib
import json
from pathlib import Path

import joblib
import numpy as np
from pipeline import BANDS


def predict_samples(model_path, csv_path, units, output):
    """Retain source columns and flag out-of-training-range/negative predictions."""
    if units not in ('reflectance', 'dn'):
        raise ValueError('units must be reflectance or dn')
    with Path(csv_path).open(encoding='utf-8-sig') as stream:
        reader = csv.DictReader(stream)
        fields = reader.fieldnames or []
        if not set(BANDS).issubset(fields):
            raise ValueError('Input must contain B2, B3, B4 and B8')
        if set(fields) & {'predicted_depth_m', 'outside_training_range', 'negative_prediction'}:
            raise ValueError('Input contains reserved output column names')
        rows = list(reader)
    if not rows:
        raise ValueError('Input CSV is empty')
    x = np.array([[float(row[band]) for band in BANDS] for row in rows])
    if units == 'dn':
        x = x / 10000.0
    if not np.isfinite(x).all() or (x < 0).any() or (x > 1).any():
        raise ValueError('Expected finite reflectance in [0,1]; verify scale and offset')
    # joblib uses pickle: only load artifacts created by you or a trusted source.
    artifact = joblib.load(model_path)
    if tuple(artifact.get('bands', ())) != BANDS or artifact.get('input_units') != 'reflectance':
        raise ValueError('Model feature order or units do not match this pipeline')
    model = artifact['model']
    predictions = model.predict(x)
    if not np.isfinite(predictions).all():
        raise ValueError('Model returned non-finite predictions')
    scaler = model[0]
    outside = ((x < scaler.data_min_) | (x > scaler.data_max_)).any(axis=1)
    output = Path(output)
    output.parent.mkdir(parents=True, exist_ok=True)
    with output.open('w', newline='', encoding='utf-8') as stream:
        writer = csv.DictWriter(stream, fieldnames=fields + ['predicted_depth_m', 'outside_training_range', 'negative_prediction'])
        writer.writeheader()
        for row, depth, flag in zip(rows, predictions, outside):
            writer.writerow({**row, 'predicted_depth_m': float(depth),
                             'outside_training_range': bool(flag), 'negative_prediction': bool(depth < 0)})
    report = dict(count=len(rows), units=units, outside_training_range=int(outside.sum()),
                  negative_predictions=int((predictions < 0).sum()),
                  input_sha256=hashlib.sha256(Path(csv_path).read_bytes()).hexdigest(),
                  model_sha256=hashlib.sha256(Path(model_path).read_bytes()).hexdigest(),
                  note='Predictions are not accuracy measurements. Negative outputs are flagged, not silently clipped.')
    output.with_suffix('.metadata.json').write_text(json.dumps(report, indent=2), encoding='utf-8')
    return report


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('model', type=Path, help='Trusted .joblib generated by pipeline.py')
    parser.add_argument('csv', type=Path)
    parser.add_argument('--units', choices=['reflectance', 'dn'], required=True)
    parser.add_argument('--output', type=Path, default=Path('runs/inference.csv'))
    args = parser.parse_args()
    predict_samples(args.model, args.csv, args.units, args.output)
    print(args.output)
